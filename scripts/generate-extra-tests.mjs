/**
 * Generates the second (and third) regression case for every formula that only
 * shipped one case. The spec requires ≥ 2 automated tests per formula, and a
 * second scenario also catches "works only for the demo input" solvers.
 *
 * The generated values are committed as literals in `apps/web/extra-tests.js`
 * so they behave like any other regression expectation: if a solver changes its
 * numerics, the test fails and a reviewer must sign off on the new value.
 *
 * Run: node scripts/generate-extra-tests.mjs
 */
import { writeFile } from 'node:fs/promises';
import { FORMULAS } from '../apps/web/registry.js';
import { EXTRA_TESTS } from '../apps/web/extra-tests.js';

/** The registry merges generated cases; strip them so re-runs stay idempotent. */
const baseTests = (formula) => {
  const generated = EXTRA_TESTS[formula.id] ?? [];
  const generatedInputs = new Set(generated.map((test) => JSON.stringify(test.input)));
  return formula.tests.filter((test) => !generatedInputs.has(JSON.stringify(test.input)));
};

const NUMERIC_TOLERANCE = 1e-9;

const isFiniteNumber = (value) => typeof value === 'number' && Number.isFinite(value);

const candidatesFor = (formula, base) => {
  const candidates = [];
  for (const variable of formula.variables) {
    const value = base[variable.name];
    if (variable.type === 'number' && typeof value === 'number' && value !== 0) {
      for (const factor of [2, 0.5, 3, 1.5]) {
        candidates.push({ ...base, [variable.name]: Number((value * factor).toPrecision(12)) });
        candidates.push({ ...base, [variable.name]: Number((value + 1).toPrecision(12)) });
      }
    }
    if (variable.type === 'text' && typeof value === 'string') {
      const numeric = value
        .split(',')
        .map((part) => Number(part.trim()))
        .filter((part) => Number.isFinite(part));
      if (numeric.length > 1) {
        candidates.push({ ...base, [variable.name]: numeric.map((n) => n * 2).join(',') });
      }
    }
  }
  return candidates;
};

/** Cases whose domain constraints block automatic perturbation. */
const MANUAL_CASES = {
  shannon_entropy: {
    input: { probs: '0.25,0.25,0.25,0.25' },
    expected: { entropy_bits: 2, max_entropy: 2, efficiency_percent: 100 },
  },
  compound_interest: {
    input: { PV: 10000, rate: 8, years: 10, m: 12 },
    expected: {
      future_value: 22196.4,
      future_continuous: 22255.41,
      interest_earned: 12196.4,
      doubling_years_rule72: 9,
    },
  },
};

const lines = [];
let generated = 0;

for (const formula of FORMULAS) {
  const original = baseTests(formula);
  if (original.length >= 2) continue;
  const base = original[0].input;
  const assertedKeys = Object.keys(original[0].expected);
  let chosen = MANUAL_CASES[formula.id] ?? null;

  for (const candidate of chosen ? [] : candidatesFor(formula, base)) {
    if (JSON.stringify(candidate) === JSON.stringify(base)) continue;
    try {
      const result = formula.compute({ ...candidate });
      if (!result?.values) continue;
      // Never commit a case that produces NaN/Infinity (validate-registry rejects those).
      if (Object.values(result.values).some((value) => typeof value === 'number' && !Number.isFinite(value))) continue;
      const expected = {};
      let usable = true;
      for (const key of assertedKeys) {
        const value = result.values[key];
        if (isFiniteNumber(value)) {
          // Guard against a perturbation that changes nothing (would be a duplicate test).
          expected[key] = Number(value.toPrecision(10));
        } else if (typeof value === 'string' || typeof value === 'boolean') {
          expected[key] = value;
        } else {
          usable = false;
        }
      }
      if (!usable) continue;
      const sameAsFirst = assertedKeys.every((key) => {
        const first = original[0].expected[key];
        const second = expected[key];
        if (isFiniteNumber(first) && isFiniteNumber(second)) {
          return Math.abs(first - second) <= NUMERIC_TOLERANCE * Math.max(1, Math.abs(first));
        }
        return String(first) === String(second);
      });
      if (sameAsFirst) continue;
      chosen = { input: candidate, expected };
      break;
    } catch {
      /* candidate violates the formula domain — try the next one */
    }
  }

  if (!chosen) {
    const manual = MANUAL_CASES[formula.id];
    if (!manual) {
      console.warn(`! could not derive a second case for ${formula.id}`);
      continue;
    }
    chosen = manual;
  }
  generated += 1;
  lines.push(`  ${formula.id}: ${JSON.stringify([chosen])},`);
}

const output = `// Generated by scripts/generate-extra-tests.mjs — do not edit by hand.
// Second regression case for formulas that originally shipped a single case.
// Values are literal on purpose: changing solver numerics must fail review.
export const EXTRA_TESTS = {
${lines.join('\n')}
};
`;

await writeFile(new URL('../apps/web/extra-tests.js', import.meta.url), output);
console.log(`Extra test cases generated for ${generated} formulas.`);
