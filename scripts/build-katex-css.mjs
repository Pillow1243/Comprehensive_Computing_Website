/**
 * Inlines the KaTeX stylesheet for the formula routes.
 *
 * Formula pages are statically exported with their KaTeX markup already in the
 * HTML. Linking `katex.min.css` as a normal stylesheet made it a render-blocking
 * request on 289 pages (Lighthouse FCP 760 ms → 1515 ms), so instead the rules
 * are embedded in the page itself, with only the WOFF2 faces kept (the WOFF and
 * TTF fallbacks are dead weight for every browser this app supports).
 *
 * Outputs:
 *   lib/katex-css.generated.ts   the stylesheet as a string, imported by the page
 *   public/katex-fonts/*.woff2   the faces it references
 */
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const katexDist = path.join(root, 'node_modules', 'katex', 'dist');
const fontOut = path.join(root, 'public', 'katex-fonts');
const moduleOut = path.join(root, 'lib', 'katex-css.generated.ts');
const basePath = '/Comprehensive_Computing_Website';

const css = await readFile(path.join(katexDist, 'katex.min.css'), 'utf8');

// Keep only the WOFF2 source inside every @font-face block.
const trimmed = css.replace(
  /src:url\(fonts\/([^)]+?)\.woff2\) format\("woff2"\)(?:,url\(fonts\/[^)]+\) format\("(?:woff|truetype)"\))*/g,
  (_match, name) => `src:url(${basePath}/katex-fonts/${name}.woff2) format("woff2")`,
);

if (trimmed.includes('url(fonts/')) {
  throw new Error('KaTeX CSS still references relative font paths — update the rewrite rules.');
}

const faces = [...new Set([...trimmed.matchAll(/katex-fonts\/([^)"']+\.woff2)/g)].map((match) => match[1]))];

await rm(fontOut, { recursive: true, force: true });
await mkdir(fontOut, { recursive: true });
for (const face of faces) {
  await copyFile(path.join(katexDist, 'fonts', face), path.join(fontOut, face));
}

const banner = `/* AUTO-GENERATED by scripts/build-katex-css.mjs — do not edit. */
`;
await writeFile(
  moduleOut,
  `${banner}export const KATEX_CSS = ${JSON.stringify(trimmed)};\nexport const KATEX_FONT_FACES = ${JSON.stringify(faces)} as const;\n`,
  'utf8',
);

const copied = await readdir(fontOut);
console.log(
  `KaTeX stylesheet inlined: ${(trimmed.length / 1024).toFixed(1)} KB, ${copied.length} WOFF2 faces copied.`,
);
