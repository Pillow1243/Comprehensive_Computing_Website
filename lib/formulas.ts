export type Difficulty = 'basic' | 'intermediate' | 'advanced';

export interface FormulaVariable {
  name: string;
  label_fa: string;
  label_en: string;
  type: 'number' | 'text' | 'select' | 'boolean';
  unit: string | null;
  required: boolean;
  default?: string | number | boolean;
  min?: number;
  max?: number;
  step?: number;
  options?: string[];
}

export interface FormulaOutput {
  name: string;
  label_fa: string;
  label_en: string;
  unit: string | null;
}

export interface FormulaTest {
  input: Record<string, number | string | boolean>;
  expected: Record<string, unknown>;
}

export interface PlotSpec {
  type?: string;
  [key: string]: unknown;
}

export interface ComputeResult {
  values: Record<string, unknown>;
  steps: string[];
}

/** Lightweight metadata that ships with the app shell. */
export interface FormulaMeta {
  id: string;
  name_fa: string;
  name_en: string;
  /** Present only after `loadDescriptions()` resolves (kept out of first load). */
  description_fa?: string;
  category_path: string[];
  tags: string[];
  difficulty: Difficulty;
  test_count: number;
}

/** Full metadata, lazy-loaded per formula page. */
export interface Formula extends FormulaMeta {
  formula_latex: string;
  variables: FormulaVariable[];
  outputs: FormulaOutput[];
  plot_spec?: PlotSpec | null;
  examples: Array<Record<string, number | string | boolean>>;
  version: string;
  validated: boolean;
}

export interface CategoryNode {
  id: string;
  fa: string;
  en: string;
  icon: string;
  children: string[];
}

/**
 * The UI only needs metadata. Executable solvers live in the computation worker
 * (`workers/compute-worker.ts`), which keeps ~59 KB gzip of solver code out of
 * the first-load bundle. `formula-index.json` is generated by
 * `scripts/build-formula-index.mjs` from the very same registry, and
 * `npm run validate-registry` guarantees the two stay in sync.
 */
export const FORMULAS = RAW_INDEX as FormulaMeta[];
export const CATEGORIES = RAW_CATEGORIES as CategoryNode[];

export const getFormula = (id: string): FormulaMeta | undefined =>
  FORMULAS.find((formula) => formula.id === id);

/**
 * Lazily merges list metadata with the detail manifest.
 * Keeps ~15 KB gzip of variable/output metadata off every non-formula route.
 */
export const loadFormula = async (id: string): Promise<Formula | undefined> => {
  const meta = getFormula(id);
  if (!meta) return undefined;
  const { default: details } = await import('@/packages/formula-registry/formula-details.json');
  const detail = (details as unknown as Record<string, Omit<Formula, keyof FormulaMeta>>)[id];
  if (!detail) return undefined;
  return { ...meta, ...detail };
};

export const formulaCategory = (formula: FormulaMeta, lang: Language): string =>
  categoryPathLabel(formula.category_path, lang);

export const formulaName = (formula: FormulaMeta, lang: Language): string =>
  lang === 'fa' ? formula.name_fa : formula.name_en;

export const formulaDescription = (formula: FormulaMeta, lang: Language): string => {
  if (lang === 'fa') return formula.description_fa ?? `${formula.name_fa} — ${formula.category_path.join(' · ')}`;
  return `A validated, step-by-step ${formula.name_en} solver with unit-aware inputs, plotting and saved history.`;
};

export const variableLabel = (variable: FormulaVariable, lang: Language): string =>
  lang === 'fa' ? variable.label_fa : variable.label_en;

export const outputLabel = (output: FormulaOutput, lang: Language): string =>
  lang === 'fa' ? output.label_fa : output.label_en;

