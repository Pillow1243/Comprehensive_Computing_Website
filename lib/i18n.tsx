/* English/Arabic dictionaries live in lib/dictionaries.ts and load lazily (v4.1). */

export interface I18nContextValue {
  lang: Language;
  dir: Direction;
  isRtl: boolean;
  numerals: Numerals;
  t: (key: string, vars?: Record<string, string | number>) => string;
  format: (value: unknown, decimals?: number) => string;
  categoryLabel: (path: string[]) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useAppStore((state) => state.settings.language);
  const numerals = useAppStore((state) => state.settings.numerals);

  const lang = (['fa', 'en', 'ar'] as const).includes(language) ? language : 'fa';
  const dir: Direction = isRtlLanguage(lang) ? 'rtl' : 'ltr';

  // English/Arabic dictionaries are a lazy chunk (lib/dictionaries.ts);
  // until it lands, lookups fall back to Persian — the SSR language anyway.
  const [lazyDictionary, setLazyDictionary] = useState<Dictionary | null>(null);
  useEffect(() => {
    if (lang === 'fa') return;
    let cancelled = false;
    void import('@/lib/dictionaries')
      .then((module) => {
        if (!cancelled) setLazyDictionary(module.dictionaries[lang as 'en' | 'ar'] ?? null);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [lang]);

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = dir;
    root.dataset.language = lang;
  }, [lang, dir]);

  const value = useMemo<I18nContextValue>(() => {
    const dictionary = lang === 'fa' ? fa : (lazyDictionary ?? fa);
    const fallback = fa;
    const t: I18nContextValue['t'] = (key, vars) => {
      const template = dictionary[key] ?? fallback[key] ?? key;
      if (!vars) return template;
      return Object.entries(vars).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
        template,
      );
    };
    const format = (input: unknown, decimals = 6) => {
      // Lazy import avoids a cycle: utils has no dependency on i18n.
      const raw =
        typeof input === 'number'
          ? Number.isFinite(input)
            ? new Intl.NumberFormat('en-US', { maximumFractionDigits: Math.min(decimals, 20) }).format(
                input,
              )
            : String(input)
          : String(input ?? '—');
      return localizeDigits(raw, lang, numerals);
    };
    const categoryLabel = (path: string[]) => categorySegment(path[path.length - 1] ?? '', lang);
    return { lang, dir, isRtl: dir === 'rtl', numerals, t, format, categoryLabel };
  }, [lang, dir, numerals, lazyDictionary]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside <I18nProvider>');
  return context;
}

export const translateCategory = (path: string[], lang: Language): string => {
  if (!path.length) return '';
  return categorySegment(path[path.length - 1], lang);
};
