const titleCase = (name: string) =>
  name.replaceAll('_', ' ').replace(/\b\w/g, (char) => char.toUpperCase());

/**
 * Best-effort label for a result key: Persian dictionary → prettified Latin.
 */
export const humanizeOutput = (name: string, labelFa: string | undefined, lang: string): string => {
  if (lang === 'fa' && (!labelFa || labelFa === name)) return LABELS[name] ?? name.replaceAll('_', ' ');
  if (labelFa && labelFa !== name) return labelFa;
  return titleCase(name);
};

export const hasHumanLabel = (name: string) => name in LABELS;
